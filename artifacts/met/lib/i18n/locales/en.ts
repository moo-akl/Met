// We use a deep-partial type for non-en locales so they can omit any key
// (single string or whole namespace) and i18n-js falls back to the en value
// at runtime via `enableFallback`. The `en` file itself stays the source of
// truth for the full key set.
type DeepPartial<T> = {
  [K in keyof T]?: T[K] extends object ? DeepPartial<T[K]> : T[K];
};
export type LocaleTree = DeepPartial<typeof en>;
