import type { GlobalVenueProspectData } from "./globalVenueProspects";

type EnglishVenueSeed = {
  id: string;
  name: string;
  location: string;
  category: string;
  websiteUrl: string;
  osmPath: string;
  fitEvidenceQuote: string;
  fitReason: string;
  email?: string;
  emailEvidenceUrl?: string;
  emailEvidenceQuote?: string;
  contactUrl?: string;
  outreachHoldReason?: string;
};

const NO_PUBLIC_EMAIL_HOLD =
  "No general business email was verified on the official venue site. Review the linked contact route before outreach.";

function makeContactFormDraft(seed: EnglishVenueSeed): string {
  return [
    `Hello, team at ${seed.name}.`,
    "I’m reaching out from Met, a recently launched tool that helps venues connect with guests, build relationships, and give guests reasons to return.",
    seed.fitReason,
    "We’re adding venues worldwide. If this sounds relevant, please let me know the right person to contact.",
    "Best,",
    "The Met team",
  ].join("\n\n");
}

function makeProspect(seed: EnglishVenueSeed): GlobalVenueProspectData {
  const email = seed.email?.trim() ?? "";
  const emailVerified = email.length > 0;
  const outreachHoldReason =
    seed.outreachHoldReason?.trim() || (!emailVerified ? NO_PUBLIC_EMAIL_HOLD : "");

  return {
    id: seed.id,
    name: seed.name,
    location: seed.location,
    category: seed.category,
    email,
    websiteUrl: seed.websiteUrl,
    emailEvidenceUrl: emailVerified ? seed.emailEvidenceUrl ?? seed.websiteUrl : "",
    emailEvidenceQuote: emailVerified ? seed.emailEvidenceQuote ?? email : "",
    contactUrl: seed.contactUrl ?? (emailVerified ? `mailto:${email}` : seed.websiteUrl),
    ...(outreachHoldReason ? { outreachHoldReason } : {}),
    ...(!emailVerified ? { contactFormDraft: makeContactFormDraft(seed) } : {}),
    fitEvidenceUrl: seed.websiteUrl,
    fitEvidenceQuote: seed.fitEvidenceQuote,
    discoverySourceUrl: `https://www.openstreetmap.org/${seed.osmPath}`,
    outreachLanguage: "en",
    fitReason: seed.fitReason,
  };
}

